#!/usr/bin/env python3
"""Build the site's catalogue files in data/ (no build step is needed to *serve* the site; this only writes data files).

    python3 tools/build_catalog.py                 # after hand-editing data/<category>.js: rebuild data/index.js
    python3 tools/build_catalog.py --from <dir>    # rebuild data/<category>.js from collected JSON files in <dir>

data/<category>.js holds every model of that category with its full specification table:
    window.CATALOG["ac"] = [{"id", "sub", "brand", "name", "model", "hl": [...], "specs": [[group, [[key, value], ...]], ...]}, ...]
data/index.js holds only what every page needs: per category the product count, the sub-types with counts,
the brands, and four featured products (without specs) for the home page.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
CATEGORIES = ["batteries", "inverters", "chargers", "electric-scooters", "ac", "refrigerators", "washing-machines"]

# Collected sub-type labels -> the label the site uses (matches config.js types where one exists).
SUB_ALIASES = {
    "inverters": {"Hybrid Inverter": "Hybrid", "Hybrid Inverters": "Hybrid", "Hybrid Solar Inverter": "Hybrid"},
    "batteries": {"Solar Battery": "Lithium Solar Battery", "LFP Battery": "LFP Battery Pack", "ESS Battery": "ESS Inverter Battery"},
    "electric-scooters": {"Low Speed Scooter": "Low Speed", "High Speed Scooter": "High Speed"},
}
# Menu order for sub-types per category; anything not listed follows alphabetically.
SUB_ORDER = {
    "batteries": ["LFP Battery Pack", "Lithium Solar Battery", "ESS Inverter Battery", "EV Battery Pack", "LFP Cell", "NMC Cell"],
    "chargers": ["Lithium Charger", "Fast Charger"],
    "electric-scooters": ["Low Speed", "High Speed"],
    "ac": ["Split AC", "Window AC", "Cassette AC", "Tower AC", "Ductable AC", "Portable AC"],
    "refrigerators": ["Single Door", "Double Door", "Convertible", "Bottom Freezer", "Side by Side", "Multi Door / French Door"],
    "washing-machines": ["Front Load", "Top Load", "Semi Automatic", "Washer Dryer"],
}
FORBIDDEN = re.compile(r"\barb\b|arbaccessories|arb accessories|₹|\brs\.?\s*\d|\bmrp\b|\bprice\b", re.I)


def fail(msg: str) -> None:
    sys.exit(f"build_catalog: {msg}")


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def clean(v) -> str:
    return re.sub(r"\s+", " ", str(v)).strip()


def normalise(raw: dict) -> dict:
    """One collected record (see the collectors' SCHEMA.md) -> the compact shape the site reads."""
    cat = raw["category"]
    if cat not in CATEGORIES:
        fail(f"unknown category {cat!r} on {raw.get('id')}")
    sub = clean(raw["subcategory"])
    sub = SUB_ALIASES.get(cat, {}).get(sub, sub)
    specs = []
    for g in raw.get("specs") or []:
        rows = [[clean(k), clean(v)] for k, v in g.get("items", []) if clean(k) and clean(v) not in ("", "-", "NA", "N/A")]
        if rows:
            specs.append([clean(g.get("group") or "Specifications"), rows])
    p = {
        "id": slug(raw.get("id") or f"{raw.get('brand', '')} {raw.get('model') or raw['name']}"),
        "sub": sub,
        "brand": clean(raw.get("brand", "")),
        "name": clean(raw["name"]),
        "model": clean(raw.get("model", "")),
        "hl": [clean(h) for h in raw.get("highlights", []) if clean(h)][:6],
        "specs": specs,
    }
    image = clean(raw.get("image", ""))  # a local path, e.g. images/products/ac/<id>.jpg
    if image:
        if not (ROOT / image).is_file():
            fail(f"{p['id']}: image {image} not found")
        p["image"] = image
    text = json.dumps(p, ensure_ascii=False)
    m = FORBIDDEN.search(text)
    if m:
        fail(f"{p['id']}: contains {m.group(0)!r} (no ARB mentions and no prices on the site)")
    return cat, p


def sort_key(cat: str, p: dict):
    order = SUB_ORDER.get(cat, [])
    return (order.index(p["sub"]) if p["sub"] in order else len(order), p["sub"], p["brand"], p["name"])


def write_category(cat: str, products: list) -> None:
    DATA.mkdir(exist_ok=True)
    body = json.dumps(products, ensure_ascii=False, separators=(",", ":"))
    (DATA / f"{cat}.js").write_text(
        f"/* Generated by tools/build_catalog.py. Hand edits are fine: keep it valid JSON, then rerun the script to refresh data/index.js. */\n"
        f"window.CATALOG = window.CATALOG || {{}};\nwindow.CATALOG[{json.dumps(cat)}] = {body};\n", encoding="utf-8")


def read_category(path: Path) -> list:
    text = path.read_text(encoding="utf-8")
    m = re.search(r"window\.CATALOG\[[^\]]+\]\s*=\s*(\[.*\]);\s*$", text, re.S)
    if not m:
        fail(f"{path.name}: expected `window.CATALOG[\"...\"] = [...];`")
    return json.loads(m.group(1))


def featured(products: list, n: int = 4) -> list:
    """Round-robin across sub-types so the home row shows variety; specs left out to keep index.js small."""
    by_sub = {}
    for p in products:
        by_sub.setdefault(p["sub"], []).append(p)
    picks, i = [], 0
    while len(picks) < n and any(len(v) > i for v in by_sub.values()):
        picks += [v[i] for v in by_sub.values() if len(v) > i]
        i += 1
    return [{k: v for k, v in p.items() if k != "specs"} for p in picks[:n]]


def write_index() -> None:
    index = {}
    for path in sorted(DATA.glob("*.js")):
        if path.name == "index.js":
            continue
        cat = path.stem
        products = read_category(path)
        ids = [p["id"] for p in products]
        dupes = {i for i in ids if ids.count(i) > 1}
        if dupes:
            fail(f"{path.name}: duplicate ids {sorted(dupes)[:5]}")
        subs, brands = {}, {}
        for p in products:
            subs[p["sub"]] = subs.get(p["sub"], 0) + 1
            if p.get("brand"):
                brands[p["brand"]] = brands.get(p["brand"], 0) + 1
        index[cat] = {"count": len(products), "subcats": subs, "brands": brands, "featured": featured(products)}
    (DATA / "index.js").write_text(
        "/* Generated by tools/build_catalog.py from data/<category>.js. Do not edit by hand. */\n"
        f"window.CATALOG_INDEX = {json.dumps(index, ensure_ascii=False, separators=(',', ':'))};\n", encoding="utf-8")
    for cat, v in index.items():
        print(f"{cat:18} {v['count']:4} products  " + ", ".join(f"{s} {n}" for s, n in v["subcats"].items()))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="src", type=Path, help="folder of collected *.json files")
    args = ap.parse_args()
    if args.src:
        cats = {}
        for f in sorted(args.src.glob("*.json")):
            for raw in json.loads(f.read_text(encoding="utf-8")):
                cat, p = normalise(raw)
                cats.setdefault(cat, []).append(p)
        for cat, products in cats.items():
            seen = {}
            for p in products:  # the same model from two pages: keep the one with more spec rows
                old = seen.get(p["id"])
                if not old or sum(len(r) for _, r in p["specs"]) > sum(len(r) for _, r in old["specs"]):
                    seen[p["id"]] = p
            write_category(cat, sorted(seen.values(), key=lambda p: sort_key(cat, p)))
    write_index()


if __name__ == "__main__":
    main()
